'use strict';
/* Деньги: остаток долга (frontend/app.js, функция dbal).

   Берём саму рабочую функцию из программы, а не её пересказ, — иначе тест
   проверял бы сам себя. Если кто-то уберёт округление, эти проверки упадут.

   Почему это важно: дробные суммы складываются неточно. Человек брал товар
   на 85.10 и 220.20, вернул ровно 305.30 — а в остатке оставалось
   −0.00000000000006. Программа считала долг незакрытым, держала человека
   в списке должников и показывала, что магазин должен ему. */
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const src = fs.readFileSync(path.join(__dirname, '..', '..', 'frontend', 'app.js'), 'utf8');
const m = /function dbal\(id\)\{[\s\S]*?\n\}/.exec(src);   // до закрывающей скобки в начале строки
assert.ok(m, 'в программе не нашлась функция dbal — тест устарел');

// Поднимаем настоящую функцию в своём окружении: D (долги) и DT (знаки операций)
function makeDbal(ops) {
  const D = { ops };
  const DT = { give: ['дал', 1], get: ['взял', -1] };
  return new Function('D', 'DT', m[0] + ' return dbal;')(D, DT);
}
const дал = (amt) => ({ pid: 'p1', type: 'give', amt });
const взял = (amt) => ({ pid: 'p1', type: 'get', amt });

test('вернул всё до копейки — долг закрыт, а не «−0.00»', () => {
  const dbal = makeDbal([дал(85.10), дал(220.20), взял(305.30)]);
  const b = dbal('p1');
  assert.equal(b, 0, 'остаток должен быть ровно ноль, получено: ' + b);
  assert.ok(!b, 'программа проверяет закрытость через !b — ноль обязан быть «пустым»');
  assert.ok(!Object.is(b, -0) || b === 0, 'минус-ноль в долге выглядит как «магазин должен»');
});

test('мелкие дробные суммы тоже сходятся', () => {
  assert.equal(makeDbal([дал(0.1), дал(0.2), взял(0.3)])('p1'), 0);
  assert.equal(makeDbal([дал(1733.70), взял(1733.70)])('p1'), 0);
  assert.equal(makeDbal([дал(19.99), дал(19.99), дал(19.99), взял(59.97)])('p1'), 0);
});

test('человек с закрытым долгом уходит из списка должников', () => {
  // список строится отбором dbal(p.id)!==0
  const dbal = makeDbal([дал(85.10), дал(220.20), взял(305.30)]);
  assert.equal(dbal('p1') !== 0, false, 'закрывший долг не должен оставаться в списке');
});

test('настоящий долг остаётся настоящим, округление его не съедает', () => {
  assert.equal(makeDbal([дал(305.30), взял(300)])('p1'), 5.3);
  assert.equal(makeDbal([дал(100.01)])('p1'), 100.01);
  assert.equal(makeDbal([дал(0.01)])('p1'), 0.01, 'один дирам — всё ещё долг');
});

test('переплата остаётся переплатой, со знаком минус', () => {
  assert.equal(makeDbal([дал(100), взял(150.50)])('p1'), -50.5);
});

test('чужие операции в остаток не попадают', () => {
  const D = { ops: [{ pid: 'p1', type: 'give', amt: 100 }, { pid: 'p2', type: 'give', amt: 999 }] };
  const DT = { give: ['дал', 1], get: ['взял', -1] };
  const dbal = new Function('D', 'DT', m[0] + ' return dbal;')(D, DT);
  assert.equal(dbal('p1'), 100);
  assert.equal(dbal('p2'), 999);
});

test('длинная история не накапливает ошибку', () => {
  const ops = [];
  for (let i = 0; i < 300; i++) ops.push(дал(10.10));
  ops.push(взял(10.10 * 300));
  assert.equal(makeDbal(ops)('p1'), 0, 'после трёхсот записей остаток обязан сойтись');
});

/* Показ денег. Та же беда вылезала в выписке, которую отправляют человеку
   в WhatsApp: «→ баланс −0 сомони». Минус там, где всё сошлось. */
const mm = /function money\(n\)\{[\s\S]*?\n\}/.exec(src);
assert.ok(mm, 'в программе не нашлась функция money — тест устарел');
const moneyRaw = new Function('CL', mm[0] + ' return money;')(() => 'сомонӣ');
// Разделитель тысяч зависит от версии системы (бывает неразрывный пробел),
// поэтому сравниваем, приведя любые пробелы к обычному.
const money = (n) => moneyRaw(n).replace(/\s/g, ' ');

test('сошедшийся баланс печатается без минуса', () => {
  assert.equal(money(85.10 + 220.20 - 305.30), '0 сомонӣ');
  assert.equal(money(-0), '0 сомонӣ');
  assert.equal(money(0), '0 сомонӣ');
});

test('настоящие суммы печатаются как прежде', () => {
  assert.equal(money(305.3), '305,3 сомонӣ');
  assert.equal(money(-50.5), '-50,5 сомонӣ', 'переплата обязана остаться со знаком');
  assert.equal(money(0.01), '0,01 сомонӣ');
  assert.equal(money(1733.7), '1 733,7 сомонӣ');
});

test('мусор вместо суммы не ломает показ', () => {
  assert.equal(money(undefined), '0 сомонӣ');
  assert.equal(money(null), '0 сомонӣ');
  assert.equal(money('не число'), '0 сомонӣ');
});
