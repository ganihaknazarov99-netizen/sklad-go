'use strict';
/* Адрес посетителя для ограничения попыток входа. Раньше сервер брал его из
   X-Forwarded-For от кого угодно: подставь туда новый адрес на каждую попытку —
   и перебирай пароли без остановки. */
const test = require('node:test');
const assert = require('node:assert/strict');
const { clientIp } = require('../src/http');

const запрос = (peer, xff) => ({ socket: { remoteAddress: peer }, headers: xff === undefined ? {} : { 'x-forwarded-for': xff } });

test('чужой не подставит себе адрес: заголовок от постороннего не в счёт', () => {
  assert.equal(clientIp(запрос('203.0.113.7', '1.2.3.4')), '203.0.113.7');
  assert.equal(clientIp(запрос('::ffff:203.0.113.7', '1.2.3.4')), '::ffff:203.0.113.7');
});

test('за своим прокси (Caddy на этой же машине) — настоящий адрес из заголовка', () => {
  assert.equal(clientIp(запрос('127.0.0.1', '198.51.100.9')), '198.51.100.9');
  assert.equal(clientIp(запрос('::1', '198.51.100.9')), '198.51.100.9');
  assert.equal(clientIp(запрос('::ffff:127.0.0.1', '198.51.100.9')), '198.51.100.9');
});

test('через прокси подсунуть адрес тоже нельзя: берём последний — его дописал сам прокси', () => {
  assert.equal(clientIp(запрос('127.0.0.1', '1.2.3.4, 198.51.100.9')), '198.51.100.9');
});

test('без заголовка — адрес соединения, как раньше', () => {
  assert.equal(clientIp(запрос('127.0.0.1')), '127.0.0.1');
  assert.equal(clientIp(запрос('203.0.113.7')), '203.0.113.7');
});
